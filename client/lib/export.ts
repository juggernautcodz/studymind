import * as Sharing from "expo-sharing";
import * as FileSystem from "expo-file-system/legacy";
import * as Print from "expo-print";
import * as Clipboard from "expo-clipboard";
import { Platform } from "react-native";

export type ShareResult = { method: "shared" | "copied" | "downloaded" };

export async function shareOrDownload(options: {
  html: string;
  plainText: string;
  title: string;
}): Promise<ShareResult> {
  const { html, plainText, title } = options;

  if (Platform.OS === "web") {
    await Clipboard.setStringAsync(plainText);
    return { method: "copied" };
  }

  try {
    const { uri } = await Print.printToFileAsync({ html, base64: false });
    const isAvailable = await Sharing.isAvailableAsync();
    if (isAvailable) {
      await Sharing.shareAsync(uri, {
        mimeType: "application/pdf",
        dialogTitle: `Share ${title}`,
      });
      return { method: "shared" };
    }
    await Clipboard.setStringAsync(plainText);
    return { method: "copied" };
  } catch {
    await Clipboard.setStringAsync(plainText);
    return { method: "copied" };
  }
}

export interface ExportableNote {
  title: string;
  content: string;
  lectureTitle: string;
  topicName?: string;
  courseName?: string;
  createdAt: string;
}

export interface ExportableFlashcard {
  front: string;
  back: string;
  difficulty: number;
  interval: number;
  nextReview?: string;
}

export interface ExportData {
  type: "notes" | "flashcards" | "all";
  notes?: ExportableNote[];
  flashcards?: ExportableFlashcard[];
  lectureTitle: string;
  courseName?: string;
  topicName?: string;
}

function escapeHtml(text: string | undefined | null): string {
  if (!text) return "";
  return text
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#039;")
    .replace(/\n/g, "<br>");
}

function formatMarkdown(text: string | undefined | null): string {
  if (!text) return "";
  let html = escapeHtml(text);
  html = html.replace(/\*\*(.*?)\*\*/g, "<strong>$1</strong>");
  html = html.replace(/\*(.*?)\*/g, "<em>$1</em>");
  html = html.replace(/^- (.+)/gm, "<li>$1</li>");
  html = html.replace(/^(\d+)\. (.+)/gm, "<li>$2</li>");
  return html;
}

