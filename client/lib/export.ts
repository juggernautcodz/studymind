export async function exportToPdf(data: ExportData): Promise<string | null> {
  try {
    let html: string;
    switch (data.type) {
      case "notes":
        html = generateNotesHtml(data);
        break;
      case "flashcards":
        html = generateFlashcardsHtml(data);
        break;
      case "all":
        html = generateCombinedHtml(data);
        break;
    }

    const { uri } = await Print.printToFileAsync({
      html,
      base64: false,
    });

    return uri;
  } catch (error) {
    console.error("Error exporting to PDF:", error);
    return null;
  }
}

export async function shareContent(data: ExportData): Promise<boolean> {
  try {
    const isAvailable = await Sharing.isAvailableAsync();
    if (!isAvailable) {
      console.log("Sharing is not available on this device");
      return false;
    }

    const pdfPath = await exportToPdf(data);
    if (!pdfPath) {
      return false;
    }

    await Sharing.shareAsync(pdfPath, {
      mimeType: "application/pdf",
      dialogTitle: `Share ${data.lectureTitle}`,
    });

    return true;
  } catch (error) {
    console.error("Error sharing content:", error);
    return false;
  }
}

export function generatePlainText(data: ExportData): string {
  const lines: string[] = [];

  lines.push(`${data.lectureTitle}`);
  lines.push("=".repeat(data.lectureTitle.length));
  if (data.courseName) lines.push(`Course: ${data.courseName}`);
  if (data.topicName) lines.push(`Topic: ${data.topicName}`);
  lines.push(`Exported: ${new Date().toLocaleDateString()}`);
  lines.push("");

  if (data.notes && data.notes.length > 0) {
    lines.push("NOTES");
    lines.push("-".repeat(40));
    data.notes.forEach((note) => {
      lines.push(`\n## ${note.title}\n`);
      lines.push(note.content);
      lines.push("");
    });
  }

  if (data.flashcards && data.flashcards.length > 0) {
    lines.push("\nFLASHCARDS");
    lines.push("-".repeat(40));
    data.flashcards.forEach((card, i) => {
      lines.push(`\n${i + 1}. Q: ${card.front}`);
      lines.push(`   A: ${card.back}`);
    });
  }

  lines.push("\n---");
  lines.push("Generated by StudyMind");

  return lines.join("\n");
}

export async function exportToText(data: ExportData): Promise<string | null> {
  try {
    const text = generatePlainText(data);
    const filename = `${data.lectureTitle.replace(/[^a-zA-Z0-9]/g, "_")}_${data.type}.txt`;
    const path = `${FileSystem.documentDirectory}${filename}`;

    await FileSystem.writeAsStringAsync(path, text, {
      encoding: FileSystem.EncodingType.UTF8,
    });

    return path;
  } catch (error) {
    console.error("Error exporting to text:", error);
    return null;
  }
}

export async function shareAsText(data: ExportData): Promise<boolean> {
  try {
    const isAvailable = await Sharing.isAvailableAsync();
    if (!isAvailable) {
      return false;
    }

    const textPath = await exportToText(data);
    if (!textPath) {
      return false;
    }

    await Sharing.shareAsync(textPath, {
      mimeType: "text/plain",
      dialogTitle: `Share ${data.lectureTitle}`,
    });

    return true;
  } catch (error) {
    console.error("Error sharing as text:", error);
    return false;
  }
}
